"""CRM школы: управление ботом, база знаний, расписание, клиенты.

Отдельное Flask-приложение рядом с ботом, а не страница внутри него. Причина
простая: бот — процесс с длинным циклом опроса, и веб-сервер внутри него делит
с диалогами один event loop; зависший запрос к CRM ударил бы по ответам
клиентам. Общее у них — файлы: ``kb/*.yaml``, ``data/admin.db``, база диалогов.

Как правки доезжают до бота:

* база знаний — CRM пишет YAML, бот замечает изменение отпечатка каталога
  (:class:`app.core.kb_watch.KBWatcher`) и перечитывает снимок на следующем ходу;
* настройки — CRM пишет ``bot_setting``, бот читает их на каждом ходу
  (:mod:`app.admin.runtime_settings`);
* клиенты и лиды — CRM читает базу диалогов, которую пишет бот.

Перезапускать бота после правок не нужно ни разу.
"""

from typing import Any

__all__ = ["create_app"]


def __getattr__(name: str) -> Any:
    """Ленивый импорт ``create_app``.

    Пакет импортируют и ради одних только :mod:`crm.kbio` и :mod:`crm.botdb`
    (тесты, скрипты). Тянуть за ними Flask и все представления незачем.
    """
    if name == "create_app":
        from crm.app import create_app

        return create_app
    raise AttributeError(name)
