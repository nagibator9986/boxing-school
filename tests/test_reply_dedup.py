"""Бот не пересказывает то, что уже отправил карточкой.

Живой случай 03.09.2026. Клиент спросил про зал у «Рахата» и получил три
сообщения подряд: видео дороги, подпись с адресом, картой и расписанием — и
следом то же самое словами модели, с вопросом «хотите посмотреть расписание?».
Владелец: «скидывают адрес, вообще расписание, причём два раза дублирует».

Инструмент и раньше просил модель не пересказывать материал. Просьба в промпте
— не гарантия; здесь та же мысль сделана проверкой.
"""

from __future__ import annotations

import pytest

from app.core.reply_dedup import strip_card_repeats

CARD = """📍 Центр — у магазина «Рахат»
Каирбекова 24

🗺 На карте: https://2gis.kz/kostanay/geo/70000001116923405

🗓 Расписание — Центр — у магазина «Рахат»

🥊 Кикбоксинг
🕒 Пт · 19:00–20:30

Возраст группы уточнит администратор."""


# --------------------------------------------------------------------------- #
# Что убирается
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize(
    "reply",
    [
        "Зал находится по адресу улица Каирбекова, 24, в здании магазина «Рахат».",
        "📍 Центр, магазин «Рахат»\nКаирбекова, 24",
        "Адрес зала: Каирбекова 24, у магазина «Рахат».",
    ],
)
def test_retelling_the_card_is_removed(reply: str) -> None:
    """Пересказ адреса другими словами — второй экземпляр того же на экране."""
    assert strip_card_repeats(reply, [CARD]) == ""


def test_offer_of_what_was_already_sent_is_removed() -> None:
    """«Хотите расписание?» сразу после карточки с расписанием.

    Клиент только что его получил: такой вопрос читается как невнимательность.
    """
    reply = "📍 Каирбекова, 24.\n\nХотите посмотреть расписание в этом зале?"

    assert strip_card_repeats(reply, [CARD]) == ""


def test_word_forms_do_not_hide_a_repeat() -> None:
    """«магазин» и «магазина» — одно слово; точное сравнение считало их разными."""
    assert strip_card_repeats("Центр, магазин «Рахат», Каирбекова 24", [CARD]) == ""


# --------------------------------------------------------------------------- #
# Что остаётся
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize(
    "reply",
    [
        "Ждём вас на пробном занятии — скажите, какой день удобнее.",
        "Записал вашего сына Артёма на пятницу, тренер Ерлан встретит у входа.",
        "Вход со двора, у турникета скажите, что вы на пробное занятие.",
        "Абонемент на 12 занятий стоит 25 000 ₸, можно оплатить переводом.",
    ],
)
def test_a_real_next_step_survives(reply: str) -> None:
    """Снятый верный ответ — это молчащий бот, и цена такой ошибки выше.

    Проверка обязана убирать пересказ, а не всё, где упомянут зал.
    """
    assert strip_card_repeats(reply, [CARD]) == reply


def test_without_cards_nothing_changes() -> None:
    """Карточек в ходу не было — чистить нечего."""
    reply = "Каирбекова 24, у магазина «Рахат»."

    assert strip_card_repeats(reply, []) == reply


def test_partial_repeat_keeps_the_new_part() -> None:
    """Убирается только повтор: то, что клиент ещё не читал, остаётся."""
    reply = (
        "📍 Центр, магазин «Рахат»\n"
        "Каирбекова, 24\n"
        "\n"
        "Отправляю видео дороги — на нём хорошо видно вход."
    )

    assert strip_card_repeats(reply, [CARD]) == (
        "Отправляю видео дороги — на нём хорошо видно вход."
    )


def test_short_line_is_never_taken_for_a_repeat() -> None:
    """«Хорошо» и «Да» совпали бы с чем угодно — их проверка не трогает."""
    for reply in ("Хорошо.", "Да", "Конечно!"):
        assert strip_card_repeats(reply, [CARD]) == reply
