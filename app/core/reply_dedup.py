"""Чтобы бот не пересказывал то, что уже отправил карточкой.

Живой случай 03.09.2026. Клиент спросил, где зал у «Рахата». Бот отправил три
сообщения подряд: видео дороги, подпись к нему с адресом, ссылкой на 2ГИС и
расписанием — и следом своими словами «📍 Каирбекова, 24, в здании магазина
«Рахат». Хотите посмотреть расписание в этом зале?». Владелец: «скидывают адрес,
вообще расписание, причём два раза дублирует».

Инструмент уже возвращает модели прямое указание «материал отправлен отдельным
сообщением — не пересказывай его содержимое». Она его не выполнила, и это
предсказуемо: указание в промпте — просьба, а не гарантия. Здесь та же мысль
сделана проверкой.

Правил два, и оба про то, что клиент уже видит на экране:

* **Повтор.** Строка, почти все значимые слова которой есть в карточке, — это
  пересказ. Сравниваются слова, а не подстроки: «Каирбекова, 24, в здании
  магазина «Рахат»» и «Центр — у магазина «Рахат» / 📍 Каирбекова 24» не
  совпадают ни одним куском текста, хотя говорят одно и то же.
* **Предложение того, что уже отправлено.** «Хотите посмотреть расписание?»
  сразу после карточки с расписанием — вопрос, на который клиент уже получил
  ответ. Такой вопрос убирается, если карточка это содержит.

Если после чистки не осталось ничего, кроме приветствия, — ответ становится
пустым, и клиенту уходит только карточка. Это правильно: карточка и есть ответ.
"""

from __future__ import annotations

import re
from typing import Final, Iterable, Sequence

__all__ = ["strip_card_repeats"]

#: Доля значимых слов строки, при которой она считается пересказом карточки.
_REPEAT_SHARE: Final[float] = 0.8

#: Короткие строки не проверяются: «Хорошо.» или «Да» совпадут с чем угодно.
_MIN_WORDS: Final[int] = 2

#: Сколько первых букв слова берётся за основу. Русский словоизменительный:
#: «магазин» в карточке и «магазина» в пересказе — одно слово, а точное
#: сравнение считало их разными, и пересказ проходил как новая мысль.
#: Пять букв различают «тренер» и «тренировка», но склеивают падежи.
_STEM: Final[int] = 5

#: Слова, которые ничего не решают при сравнении.
_STOP_WORDS: Final[frozenset[str]] = frozenset(
    {
        "в", "во", "и", "на", "по", "у", "с", "со", "к", "от", "до", "из", "за", "для",
        "это", "этом", "этот", "эта", "там", "тут", "здесь", "вот", "же", "а", "но",
        "наш", "наша", "наше", "наши", "нашем", "вас", "вам", "вы", "мы", "он", "она",
        "есть", "будет", "также", "ещё", "еще", "или", "при", "как", "что",
    }
)

#: О чём спрашивать бессмысленно, если это уже в карточке: слово в вопросе → что
#: искать в карточке. Ключ — то, что предлагает бот, значение — признак в тексте.
_OFFER_TOPICS: Final[dict[str, tuple[str, ...]]] = {
    "расписание": ("расписание", "кесте"),
    "расписании": ("расписание", "кесте"),
    "адрес": ("📍", "адрес"),
    "карте": ("2gis", "🗺"),
    "карту": ("2gis", "🗺"),
    "видео": ("видео",),
}

#: Слова-связки, которыми обрастает пересказ адреса: «зал находится по адресу
#: улица Каирбекова, 24, в здании магазина «Рахат»». Данных они не несут, а
#: долю совпадения занижают — из-за них пересказ выглядел как новая мысль.
_FILLER_WORDS: Final[frozenset[str]] = frozenset(
    {
        "зал", "зала", "зале", "залу", "адрес", "адресу", "адреса", "улица", "улице",
        "улицы", "ул", "дом", "дома", "доме", "здание", "здании", "здания",
        "находится", "находимся", "расположен", "расположена", "расположено",
        "ждем", "ждём", "приходите", "занятия", "тренировки", "секция",
    }
)

_WORD_RE: Final[re.Pattern[str]] = re.compile(r"[^\W_]+", re.UNICODE)


def _words(text: str, *, drop_filler: bool = False) -> list[str]:
    """Значимые слова строки в нижнем регистре.

    ``drop_filler`` убирает ещё и слова-связки: при сравнении строки с карточкой
    они только разбавляют долю совпадения, а данных не несут.
    """
    words = [m.group(0).lower() for m in _WORD_RE.finditer(text)]
    skip = _STOP_WORDS | _FILLER_WORDS if drop_filler else _STOP_WORDS
    return [word[:_STEM] for word in words if word not in skip]


def _is_repeat(line: str, card_words: frozenset[str]) -> bool:
    """Почти все слова строки уже сказаны карточкой."""
    words = _words(line, drop_filler=True)
    if len(words) < _MIN_WORDS:
        return False
    hits = sum(1 for word in words if word in card_words)
    return hits / len(words) >= _REPEAT_SHARE


def _is_stale_offer(line: str, cards_lower: str) -> bool:
    """Строка предлагает то, что клиент уже получил этой же карточкой."""
    if "?" not in line:
        return False
    lowered = line.lower()
    for topic, markers in _OFFER_TOPICS.items():
        if topic in lowered and any(marker in cards_lower for marker in markers):
            return True
    return False


def strip_card_repeats(reply: str, cards: Sequence[str] | Iterable[str]) -> str:
    """Ответ модели без того, что уже ушло клиенту карточкой.

    ``cards`` — тексты, отправленные в этом же ходу инструментами. Пустой список
    означает, что чистить нечего: ответ возвращается как есть.
    """
    bodies = [card for card in (c or "" for c in cards) if card.strip()]
    if not reply or not bodies:
        return reply

    joined = "\n".join(bodies)
    card_words = frozenset(_words(joined))
    cards_lower = joined.lower()

    kept: list[str] = []
    for line in reply.splitlines():
        if not line.strip():
            kept.append(line)
            continue
        if _is_repeat(line, card_words) or _is_stale_offer(line, cards_lower):
            continue
        kept.append(line)

    return "\n".join(kept).strip()
